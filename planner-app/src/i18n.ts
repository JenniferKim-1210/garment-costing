const dict = { ko, en };
let current: Lang = 'ko';

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
}

export function t(key: Key): string {
  return dict[current][key];
}

export function tFor(lang: Lang, key: Key): string {
  return dict[lang][key];
}

export function locale(): string {
  return current === 'ko' ? 'ko-KR' : 'en-US';
}

export function fmtDate(date: Date, opts: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(locale(), opts).format(date);
}

export function fmtTime(time: string): string {
  const [h, m] = time.split(':').map(Number);
  const d = new Date(2000, 0, 1, h, m);
  return fmtDate(d, { hour: 'numeric', minute: '2-digit' });
}

export function reminderLabel(min: number | null): string {
  if (min === null) return t('none');
  if (min === 0) return t('atTime');
  if (min === 60) return t('hourBefore');
  if (min === 1440) return t('dayBefore');
  return `${min}${t('minBefore')}`;
}

export const REMIND_OPTIONS: (number | null)[] = [null, 0, 5, 10, 30, 60, 1440];
